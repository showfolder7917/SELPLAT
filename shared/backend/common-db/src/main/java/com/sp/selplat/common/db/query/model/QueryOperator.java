package com.sp.selplat.common.db.query.model;

/**
 * 通用查询操作符枚举统一约束结构化查询条件允许使用的比较方式。
 * 这里先收敛第一版最常见的等值、模糊、范围和区间比较，
 * 避免业务层继续通过手写 SQL 字符串表达筛选关系。
 */
public enum QueryOperator {

    // EQ 表示字段和值做等值匹配，适合状态、编号、主键等精确查询。
    EQ,
    // LIKE 表示字段和值做模糊匹配，适合名称、编码关键字等检索。
    LIKE,
    // GTE 表示字段和值做大于等于比较，适合起始时间和最小数值筛选。
    GTE,
    // GT 表示字段和值做严格大于比较，适合金额、数量和时间下限的排他筛选。
    GT,
    // LTE 表示字段和值做小于等于比较，适合结束时间和最大数值筛选。
    LTE,
    // LT 表示字段和值做严格小于比较，适合金额、数量和时间上限的排他筛选。
    LT,
    // BETWEEN 表示字段和值区间比较，适合日期范围和数值区间筛选。
    BETWEEN,
    // IN 表示字段属于受控非空集合，适合父记录批量解析子记录。
    IN
}
